export interface LeadScoreBreakdown {
  status12Score: number;
  decisionTimeScore: number;
  parentPhoneScore: number;
  budgetScore: number;
  worryScore: number;
  completionScore: number;
  total: number;
}

export type LeadPriority = 'Hot' | 'Warm' | 'Cold';
export type LeadStatus = 'New' | 'Contacted' | 'Counselling booked' | 'Admitted' | 'Lost';
export type CallOutcome = 'Called - No Answer' | 'Called - Interested' | 'Called - Not Interested' | 'WhatsApp Sent' | 'Email Sent' | 'Meeting Done' | 'Follow-up Scheduled';

export interface CallLogEntry {
  id: string;
  timestamp: string;        // ISO string
  outcome: CallOutcome;
  note: string;
  counsellor?: string;      // optional counsellor name
}

export interface Lead {
  id: string;
  name: string;
  phone: string;
  email?: string;
  city?: string;
  parentPhone?: string;
  fillerType: 'Student' | 'Parent';
  language: 'en' | 'kn' | 'ta' | 'ml';
  stream: string;
  budget?: string;
  percentage?: string;
  entranceExams?: string[];
  status12?: string;
  decisionTime?: string;
  worry?: string;
  preferredLocation?: string;
  relocate?: string;
  workPreference?: string;
  careerValue?: string;
  heavyMathsComfort?: string;
  bestSubjects?: string[];
  riasecScores?: Record<string, number>;
  dimensionScores?: Record<string, number>;
  profileCode?: string;
  profileName?: string;
  topCourses?: string[]; // course IDs
  scoreBreakdown?: LeadScoreBreakdown;
  leadScore: number;
  priority: LeadPriority;
  status: LeadStatus;
  bookingStatus?: {
    booked: boolean;
    date?: string;
    timeSlot?: string;
  };
  notes?: string;
  internalNotes?: string;
  callLog?: CallLogEntry[];   // timestamped call / follow-up history
  followUpDate?: string;      // ISO date string for next scheduled follow-up
  createdAt: string;
}

